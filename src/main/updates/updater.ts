/**
 * Auto-update from GitHub Releases (electron-updater).
 *
 * Deliberately conservative:
 *   - **Off in development** (`app.isPackaged` is false) — nothing to update, and electron-updater
 *     errors noisily outside a packaged app.
 *   - **Off on macOS until the build is signed.** Squirrel.Mac refuses to install an update onto an
 *     unsigned bundle, so checking would only produce an update that can never apply. Re-enable by
 *     removing the darwin guard once the Developer ID is in place.
 *   - **Never installs silently mid-session**: downloads in the background; the HUD (header badge and
 *     bottom banner) shows checking/available/downloading/ready. Installing happens only on the explicit
 *     Restart action or when the app is quitting, and the app is relaunched afterwards.
 *
 * The download is verified by electron-updater against the sha512 published in `latest.yml`, which is
 * generated by electron-builder and uploaded with each release.
 */
import { app } from 'electron';

export type UpdateStatus = 'disabled' | 'idle' | 'checking' | 'available' | 'downloading' | 'ready' | 'error';

export interface UpdateState {
  status: UpdateStatus;
  /** Version offered by the feed (available / ready). */
  version?: string;
  /** Download percentage (downloading). */
  percent?: number;
  message?: string;
}

let autoUpdater: any = null;
let state: UpdateState = { status: 'idle' };
let listener: ((state: UpdateState) => void) | null = null;
let quitUpdateStarted = false;

function setState(next: Partial<UpdateState>): void {
  state = { ...state, ...next };
  try {
    listener?.(state);
  } catch {
    // A UI listener must never break the updater.
  }
}

/** Why updates are unavailable in this build, or null when they are enabled. */
export function updaterDisabledReason(): string | null {
  if (!app.isPackaged) return 'development build';
  if ((process.env.HB_DISABLE_UPDATER ?? process.env.KUANG_DISABLE_UPDATER) === '1') return 'HB_DISABLE_UPDATER=1';
  if (process.platform === 'darwin') return 'macOS build is unsigned — Squirrel.Mac will not apply updates';
  return null;
}

export function updaterState(): UpdateState {
  return state;
}

/** Wire the updater and schedule checks. Safe to call once at startup. */
export async function initUpdater(onChange: (state: UpdateState) => void): Promise<void> {
  listener = onChange;

  const reason = updaterDisabledReason();
  if (reason) {
    setState({ status: 'disabled', message: reason });
    return;
  }

  try {
    ({ autoUpdater } = await import('electron-updater'));
  } catch (err: any) {
    setState({ status: 'disabled', message: `electron-updater unavailable: ${err?.message || err}` });
    return;
  }

  autoUpdater.autoDownload = true;
  autoUpdater.autoInstallOnAppQuit = false;
  autoUpdater.autoRunAppAfterInstall = true;
  autoUpdater.allowPrerelease = false;

  autoUpdater.on('checking-for-update', () => setState({ status: 'checking', message: undefined }));
  autoUpdater.on('update-available', (info: any) => setState({ status: 'available', version: info?.version }));
  autoUpdater.on('update-not-available', () => setState({ status: 'idle', message: 'up to date' }));
  autoUpdater.on('download-progress', (p: any) =>
    setState({ status: 'downloading', percent: Math.round(Number(p?.percent) || 0) })
  );
  autoUpdater.on('update-downloaded', (info: any) => setState({ status: 'ready', version: info?.version, percent: 100 }));
  autoUpdater.on('error', (err: any) => setState({ status: 'error', message: String(err?.message || err) }));

  // A downloaded update should not silently disappear into a manual quit. Install it on quit and
  // let electron-updater relaunch the app. The explicit Restart action does the same immediately.
  app.on('before-quit', (event) => {
    if (quitUpdateStarted || state.status !== 'ready') return;
    event.preventDefault();
    installUpdate();
  });

  // First check after the window has settled, then every six hours.
  const first = setTimeout(() => void checkForUpdates(), 30_000);
  first.unref?.();
  const periodic = setInterval(() => void checkForUpdates(), 6 * 60 * 60 * 1000);
  periodic.unref?.();
}

/** Ask the feed now. Returns the resulting state (never throws). */
export async function checkForUpdates(): Promise<UpdateState> {
  if (!autoUpdater) return state;
  try {
    await autoUpdater.checkForUpdates();
  } catch (err: any) {
    setState({ status: 'error', message: String(err?.message || err) });
  }
  return state;
}

/** Quit and apply a downloaded update. No-op unless something is ready. */
export function installUpdate(): boolean {
  if (!autoUpdater || state.status !== 'ready' || quitUpdateStarted) return false;
  quitUpdateStarted = true;
  setImmediate(() => {
    try {
      autoUpdater.quitAndInstall(true, true);
    } catch {
      // If install fails the app simply stays open on the old version.
      quitUpdateStarted = false;
    }
  });
  return true;
}
